//! docs/features/write-cost.md (RM-0125) WC25, growth: on the trees of
//! `specengine-eval scale --corpus-only --nodes N --seed 1` at 1 000 and
//! 4 000 nodes, a debug build, interleaved, best of three:
//!
//! - a bare walk: a warm `update` of the unchanged tree;
//! - the GET path: that walk, then a write's check over its rows
//!   (`introduced_from_rows`, no memo: the path a miss takes) of one edit, a
//!   typical part file (a `parent:`, as the generator gives almost all)
//!   gaining a mention and a section.
//!
//! The GET path's T(4 000) - T(1 000) must be at most 1.5 x the bare
//! walk's. A second run makes the same trees render an index (`[paths]
//! index` and an `index = true` generator) and edits a rendered field (a
//! title), the case the developer named: the index's global pass decodes
//! every row; a third edits one of the few part files with no `parent:` and
//! no `depends_on`. Their growth is printed against the same bar, never
//! asserted, for the spec's record.
//!
//! M: the decode at step 4 restored (the GET path grows with the corpus).
//!
//! The run writes only under its scratch directory, with scratch `HOME` and
//! `XDG_DATA_HOME`.

mod import_support;

use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use import_support::{Scratch, eval, stderr};
use specengine_store::{
    CheckSetup, IndexWriter as _, NamedBytes, SetupFiles, SqliteIndex, WorkingTree,
    default_baseline, introduced_from_rows, load_check,
};

const SIZES: [usize; 2] = [1_000, 4_000];
const TODAY: &str = "2026-11-15";
/// GET growth <= FACTOR x walk growth.
const FACTOR: f64 = 1.5;

/// The tree of `nodes` under `scratch`, generated by the binary.
fn tree(scratch: &Scratch, nodes: usize) -> PathBuf {
    let out = scratch.join(&format!("out-{nodes}"));
    let home = scratch.join("home");
    let xdg = scratch.join("xdg");
    for dir in [&out, &home, &xdg] {
        fs::create_dir_all(dir).expect("a scratch directory");
    }
    let output = eval()
        .env("HOME", &home)
        .env("XDG_DATA_HOME", &xdg)
        .arg("scale")
        .arg("--out")
        .arg(&out)
        .args([
            "--corpus-only",
            "--nodes",
            &nodes.to_string(),
            "--seed",
            "1",
        ])
        .output()
        .expect("specengine-eval runs");
    assert!(output.status.success(), "scale: {}", stderr(&output));
    fs::canonicalize(out.join(format!("scale/synthetic/n{nodes}/tree"))).expect("the tree")
}

/// The kind of part file edited.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Shape {
    /// A part file as the generator makes almost all of them: a `parent:`
    /// (and often a `depends_on`), so a cycle pass reruns whole.
    Typical,
    /// One of the few holding neither `parent:` nor `depends_on`.
    Unlinked,
}

/// One tree, walked: its index, setup and the edit.
struct Sized {
    root: PathBuf,
    config: NamedBytes,
    baseline: Option<NamedBytes>,
    setup: CheckSetup,
    index: SqliteIndex,
    path: String,
    patched: Vec<u8>,
}

impl Sized {
    fn new(root: PathBuf, db: &Path, render: bool, shape: Shape) -> Self {
        if render {
            let config = root.join("specengine.toml");
            let text = fs::read_to_string(&config).expect("the config");
            let text = text.replacen("[paths]\n", "[paths]\nindex = \"areas/INDEX.md\"\n", 1)
                + "\n[[generators]]\ncommand = \"spec export index\"\nwrites  = [\"areas/INDEX.md\"]\nindex   = true\n";
            fs::write(&config, text).expect("the config");
        }
        let config = NamedBytes::read("specengine.toml", &root.join("specengine.toml"));
        let baseline = default_baseline(&root);
        let setup = load_check(&config, baseline.as_ref()).expect("the setup");
        let mut index = SqliteIndex::open(db, "synthetic", &root).expect("open");
        let tree = WorkingTree::new(&root, &setup.project.paths).expect("a tree");
        index.update(&tree, &setup.project.scheme).expect("a walk");
        // A part file well inside the tree: the 10th of the first area.
        let mut parts: Vec<PathBuf> = Vec::new();
        collect(&root.join("areas"), &mut parts);
        parts.sort();
        // A part file of the kind `shape` names: the 11th typical one, or the
        // first that holds no `parent:` and no `depends_on`.
        let part = parts
            .iter()
            .filter(|path| path.file_name().is_some_and(|name| name != "README.md"))
            .filter(|path| {
                let text = fs::read_to_string(path).unwrap_or_default();
                let front = text.split("\n---\n").next().unwrap_or("");
                let linked = front.contains("depends_on") || front.contains("parent:");
                linked == (shape == Shape::Typical)
            })
            .nth(if shape == Shape::Typical { 10 } else { 0 })
            .expect("a part file of the shape")
            .clone();
        let path = part
            .strip_prefix(&root)
            .expect("under the root")
            .to_str()
            .expect("UTF-8")
            .to_owned();
        let text = fs::read_to_string(&part).expect("the part file");
        let patched = if render {
            match text.lines().find(|line| line.starts_with("title:")) {
                Some(title) => text.replacen(title, "title: A renamed part", 1),
                None => text.replacen("# ", "# Renamed ", 1),
            }
        } else {
            format!("{text}\nSee P-000001 and P-000002.\n\n## Probe\n\nA new section.\n")
        };
        Self {
            root,
            config,
            baseline,
            setup,
            index,
            path,
            patched: patched.into_bytes(),
        }
    }

    fn walk(&mut self) -> Duration {
        let tree = WorkingTree::new(&self.root, &self.setup.project.paths).expect("a tree");
        let started = Instant::now();
        self.index
            .update(&tree, &self.setup.project.scheme)
            .expect("a warm walk");
        started.elapsed()
    }

    fn get(&mut self) -> Duration {
        let tree = WorkingTree::new(&self.root, &self.setup.project.paths).expect("a tree");
        let started = Instant::now();
        self.index
            .update(&tree, &self.setup.project.scheme)
            .expect("a warm walk");
        let found = introduced_from_rows(
            Some(&self.index),
            &tree,
            &self.setup,
            SetupFiles {
                config: &self.config,
                baseline: self.baseline.as_ref(),
            },
            TODAY,
            &self.path,
            self.patched.clone(),
        );
        let elapsed = started.elapsed();
        assert!(
            !found.doubted,
            "{}: nothing differs from its row",
            self.path
        );
        elapsed
    }
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).expect("a directory").flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "md") {
            out.push(path);
        }
    }
}

/// `(walk 1k, walk 4k, get 1k, get 4k)`: best of three, interleaved.
fn timed(scratch: &Scratch, render: bool, shape: Shape) -> [Duration; 4] {
    let mut sized: Vec<Sized> = SIZES
        .iter()
        .map(|&nodes| {
            let root = tree(scratch, nodes);
            let db = scratch.join(&format!("index-{nodes}-{render}.db"));
            Sized::new(root, &db, render, shape)
        })
        .collect();
    let mut best = [Duration::MAX; 4];
    for _ in 0..3 {
        for (at, one) in sized.iter_mut().enumerate() {
            best[at] = best[at].min(one.walk());
            best[2 + at] = best[2 + at].min(one.get());
        }
    }
    best
}

fn growth(best: [Duration; 4]) -> (f64, f64) {
    let ms = |duration: Duration| duration.as_secs_f64() * 1_000.0;
    (ms(best[1]) - ms(best[0]), ms(best[3]) - ms(best[2]))
}

#[test]
fn wc25_the_get_paths_growth_is_the_walks() {
    let scratch = Scratch::new("wc25");
    let best = timed(&scratch, false, Shape::Typical);
    let (walk, get) = growth(best);
    eprintln!(
        "WC25: walk {:?} -> {:?} (+{walk:.1} ms); GET path {:?} -> {:?} (+{get:.1} ms); bar \
         {:.1} ms",
        best[0],
        best[1],
        best[2],
        best[3],
        FACTOR * walk
    );
    assert!(
        get <= FACTOR * walk.max(1.0),
        "the GET path grows {get:.1} ms from 1 000 to 4 000 nodes, the bare walk {walk:.1} ms: \
         more than {FACTOR} x"
    );
}

/// The developer's case, printed for the spec: an index rendered, a title
/// edited (the global pass decodes every row). Not asserted.
#[test]
fn wc25_with_an_index_rendered_is_printed() {
    let scratch = Scratch::new("wc25-render");
    let best = timed(&scratch, true, Shape::Typical);
    let (walk, get) = growth(best);
    eprintln!(
        "WC25 (index rendered, a title edited): walk {:?} -> {:?} (+{walk:.1} ms); GET path \
         {:?} -> {:?} (+{get:.1} ms); the bar would be {:.1} ms: {}",
        best[0],
        best[1],
        best[2],
        best[3],
        FACTOR * walk,
        if get <= FACTOR * walk.max(1.0) {
            "within"
        } else {
            "over"
        }
    );
}

/// The same with the edited part file one of the few holding neither
/// `parent:` nor `depends_on` (no cycle pass reruns), printed for the spec.
/// Not asserted.
#[test]
fn wc25_with_an_unlinked_part_file_is_printed() {
    let scratch = Scratch::new("wc25-unlinked");
    let best = timed(&scratch, false, Shape::Unlinked);
    let (walk, get) = growth(best);
    eprintln!(
        "WC25 (a part file with no parent: and no depends_on): walk {:?} -> {:?} (+{walk:.1} ms); GET path {:?} \
         -> {:?} (+{get:.1} ms); the bar would be {:.1} ms: {}",
        best[0],
        best[1],
        best[2],
        best[3],
        FACTOR * walk,
        if get <= FACTOR * walk.max(1.0) {
            "within"
        } else {
            "over"
        }
    );
}
